import { readFileSync } from 'node:fs';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { VitePWA } from 'vite-plugin-pwa';
import { APP_DESCRIPTION, APP_NAME, AUTHOR } from './src/brand/info.ts';
import { DEFAULT_MARK_BG } from './src/brand/mark.ts';
import { Readable } from 'node:stream';
import type { ReadableStream as NodeReadableStream } from 'node:stream/web';
import {
  audioContentType,
  isAllowedJamendoUrl,
  JAMENDO_STORAGE_HOST,
  PASS_THROUGH_HEADERS,
  REWRITTEN_HOST_NUMBERS,
} from './api/_jamendo.ts';

const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')) as { version: string };

/** Fills %APP_NAME% / %APP_DESCRIPTION% / %APP_AUTHOR% in index.html from src/brand/info.ts. */
function brandHtml(): Plugin {
  const escapeHtml = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
  return {
    name: 'brand-html',
    transformIndexHtml: (html) =>
      html
        .replaceAll('%APP_NAME%', escapeHtml(APP_NAME))
        .replaceAll('%APP_DESCRIPTION%', escapeHtml(APP_DESCRIPTION))
        .replaceAll('%APP_AUTHOR%', escapeHtml(AUTHOR.name)),
  };
}

/**
 * Local equivalents of the Vercel setup (vercel.json + api/jamendo-download.ts), so Jamendo
 * downloads also work in `npm run dev` / `npm run preview`:
 *   /jamendo-dl/prod-N/...        → https://prod-N.storage.jamendo.com/... (proxy)
 *   /api/jamendo-download?url=…   → same allowlisted streaming fetch as the Edge Function
 */
const jamendoProxy = Object.fromEntries(
  REWRITTEN_HOST_NUMBERS.map((n) => [
    `/jamendo-dl/prod-${n}`,
    {
      target: `https://prod-${n}.storage.jamendo.com`,
      changeOrigin: true,
      rewrite: (path: string) => path.replace(new RegExp(`^/jamendo-dl/prod-${n}`), '') || '/',
    },
  ]),
);

function jamendoDownloadMiddleware(): Plugin {
  const handle = async (req: import('node:http').IncomingMessage, res: import('node:http').ServerResponse) => {
    const target = isAllowedJamendoUrl(new URL(req.url ?? '', 'http://local').searchParams.get('url'));
    if (!target) {
      res.statusCode = 403;
      res.end('Only Jamendo storage URLs can be fetched here.');
      return;
    }
    try {
      const range = req.headers.range;
      const upstream = await fetch(target, { headers: range ? { range } : {}, redirect: 'follow' });
      if (!JAMENDO_STORAGE_HOST.test(new URL(upstream.url).hostname)) {
        res.statusCode = 502;
        res.end('Unexpected redirect.');
        return;
      }
      res.statusCode = upstream.status;
      for (const h of PASS_THROUGH_HEADERS) {
        const v = upstream.headers.get(h);
        if (v) res.setHeader(h, v);
      }
      res.setHeader('content-type', audioContentType(upstream.headers.get('content-type'), target));
      if (!upstream.body) return void res.end();
      Readable.fromWeb(upstream.body as unknown as NodeReadableStream).pipe(res);
    } catch {
      res.statusCode = 502;
      res.end('Jamendo storage could not be reached.');
    }
  };
  return {
    name: 'jamendo-download-dev',
    configureServer: (server) => void server.middlewares.use('/api/jamendo-download', (req, res) => void handle(req, res)),
    configurePreviewServer: (server) =>
      void server.middlewares.use('/api/jamendo-download', (req, res) => void handle(req, res)),
  };
}

export default defineConfig({
  plugins: [
    react(),
    tailwindcss(),
    brandHtml(),
    jamendoDownloadMiddleware(),
    VitePWA({
      // New versions install in the background and take over on the next launch/navigation.
      // (No forced reload, so playback is never interrupted by an update.)
      registerType: 'autoUpdate',
      injectRegister: 'script-defer',
      // Icons live in public/icons (generated by `npm run icons`); the glob below precaches them.
      manifest: {
        name: APP_NAME,
        short_name: APP_NAME,
        description: APP_DESCRIPTION,
        // "author" isn't a standard manifest member; kept as requested (browsers ignore it).
        // @ts-expect-error -- non-standard field
        author: AUTHOR.name,
        id: '/',
        start_url: '/',
        scope: '/',
        display: 'standalone',
        orientation: 'portrait',
        background_color: '#000000',
        theme_color: DEFAULT_MARK_BG, // default accent
        icons: [
          { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
          { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
          { src: '/icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        /*
         * Precached: the app shell only (built JS/CSS/HTML, fonts, our own icons).
         * Runtime: exactly ONE rule, for the Offline section's own media at /offline-media/
         * (downloaded Jamendo/Audius tracks and imported files, put there by the app in
         * src/offline/db.ts). It is CacheOnly (never touches the network) and supports byte
         * ranges, which audio playback needs. There is no rule for anything else, so the
         * service worker never stores or serves Spotify API responses (api.spotify.com),
         * auth/token requests (accounts.spotify.com), the playback SDK or cover images, and
         * tokens (localStorage) are never seen by it.
         */
        globPatterns: ['**/*.{js,css,html,woff2,svg,png}'],
        runtimeCaching: [
          {
            urlPattern: ({ url, sameOrigin }) => sameOrigin && url.pathname.startsWith('/offline-media/'),
            handler: 'CacheOnly',
            options: {
              cacheName: 'mustify-offline-media', // must match MEDIA_CACHE in src/offline/db.ts
              rangeRequests: true,
            },
          },
        ],
        // Client-side routes (including /callback?code=…) get the cached app shell.
        navigateFallback: '/index.html',
        navigateFallbackDenylist: [/^\/offline-media\//],
        cleanupOutdatedCaches: true,
        clientsClaim: true,
        skipWaiting: true,
      },
      devOptions: { enabled: false },
    }),
  ],
  define: {
    __APP_VERSION__: JSON.stringify(pkg.version),
  },
  server: {
    proxy: jamendoProxy,
    // Spotify does not accept "localhost" redirect URIs, so the loopback IP is used.
    // strictPort: fail rather than silently moving to 5174, which would break the redirect URI.
    host: '127.0.0.1',
    port: 5173,
    strictPort: true,
  },
  preview: {
    proxy: jamendoProxy,
    host: '127.0.0.1',
    port: 5173,
    strictPort: true,
  },
});
